"""Local web/API bridge for the C Student Index Recovery engine."""
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import json
import os
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "backend.c"
EXECUTABLE = ROOT / "recovery_engine.exe" if os.name == "nt" else ROOT / "recovery_engine"
HOST, PORT = "127.0.0.1", 8000


def compile_engine():
    compiler = shutil.which("gcc") or shutil.which("clang")
    if not compiler:
        raise RuntimeError(
            "A C compiler was not found. Install GCC (for example, MinGW-w64), "
            "add gcc to PATH, then run `python app.py` again."
        )
    command = [compiler, "-std=c11", "-Wall", "-Wextra", "-O2", str(SOURCE), "-o", str(EXECUTABLE)]
    completed = subprocess.run(command, capture_output=True, text=True)
    if completed.returncode:
        raise RuntimeError("C compilation failed:\n" + completed.stderr)


def c_recover(fragments):
    lines = [str(len(fragments))]
    for fragment in fragments:
        left = -1 if fragment.get("left") is None else fragment["left"]
        right = -1 if fragment.get("right") is None else fragment["right"]
        lines.append(f"{fragment['root']} {left} {right}")
    completed = subprocess.run(
        [str(EXECUTABLE)], input="\n".join(lines) + "\n", capture_output=True,
        text=True, timeout=5,
    )
    if completed.returncode:
        raise RuntimeError("Recovery engine exited unexpectedly: " + completed.stderr.strip())
    output = completed.stdout.strip()
    if output.startswith("ERR|"):
        return {"ok": False, "reason": output[4:]}
    fields = output.split("|", 5)
    if len(fields) != 6 or fields[0] != "OK":
        raise RuntimeError("The C engine returned an unreadable response.")
    root_value, used, total_nodes = map(int, fields[1:4])
    inorder = [int(value) for value in fields[4].split(",") if value]
    nodes = []
    for encoded in fields[5].split(";"):
        if encoded:
            value, left, right = map(int, encoded.split(","))
            nodes.append({"value": value, "leftIndex": left, "rightIndex": right})
    def expand(index):
        if index < 0:
            return None
        node = nodes[index]
        return {
            "value": node["value"],
            "left": expand(node["leftIndex"]),
            "right": expand(node["rightIndex"]),
        }
    return {
        "ok": True, "root": root_value, "used": used, "total": len(fragments),
        "nodeCount": total_nodes, "inorder": inorder, "tree": expand(0),
        "log": [
            "C recovery engine identified the unique final root.",
            "Fragments were joined only at matching leaf and root IDs.",
            f"All {used} fragments were used exactly once.",
            "Full-tree BST range validation passed.",
            "Inorder traversal generated by the C engine.",
        ],
    }


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def do_POST(self):
        if self.path != "/api/recover":
            self.send_error(404, "Unknown API endpoint")
            return
        try:
            size = int(self.headers.get("Content-Length", "0"))
            if size <= 0 or size > 100_000:
                raise ValueError("Request body is missing or too large.")
            payload = json.loads(self.rfile.read(size))
            fragments = payload.get("fragments") if isinstance(payload, dict) else None
            if not isinstance(fragments, list) or not 1 <= len(fragments) <= 100:
                raise ValueError("Provide between 1 and 100 fragments.")
            clean = []
            for index, item in enumerate(fragments, start=1):
                if not isinstance(item, dict):
                    raise ValueError(f"Fragment {index} must be an object.")
                row = {}
                for key in ("root", "left", "right"):
                    value = item.get(key)
                    if key == "root" and value is None:
                        raise ValueError(f"Fragment {index} is missing its root ID.")
                    if value is not None and (isinstance(value, bool) or not isinstance(value, int)):
                        raise ValueError(f"Fragment {index} {key} ID must be a whole number.")
                    row[key] = value
                clean.append(row)
            result = c_recover(clean)
            self.send_json(200, result)
        except (ValueError, json.JSONDecodeError) as error:
            self.send_json(400, {"ok": False, "reason": str(error)})
        except (RuntimeError, subprocess.TimeoutExpired) as error:
            self.send_json(500, {"ok": False, "reason": str(error)})

    def send_json(self, status, data):
        encoded = json.dumps(data).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(encoded)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(encoded)


if __name__ == "__main__":
    try:
        compile_engine()
    except RuntimeError as error:
        print(error, file=sys.stderr)
        raise SystemExit(1)
    print(f"Student Index Recovery running at http://{HOST}:{PORT}")
    print("Press Ctrl+C to stop.")
    ThreadingHTTPServer((HOST, PORT), Handler).serve_forever()
